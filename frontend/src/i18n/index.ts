// Helper to unflatten keys (convert "a.b": "val" to {a: {b: "val"}})
const unflatten = (data: Record<string, any>) => {
  const result: Record<string, any> = {};
  for (const i in data) {
    const keys = i.split('.');
    keys.reduce((acc, key, index) => {
      if (index === keys.length - 1) {
        acc[key] = data[i];
        return acc[key];
      }
      acc[key] = acc[key] || {};
      return acc[key];
    }, result);
  }
  return result;
};

